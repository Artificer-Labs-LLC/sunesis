"""Identification: Function ID hashes and BSim similarity.

Two deterministic channels and one similarity channel:

* fid-kuna   - names Kuna applied from a .fid database during its own
               listing pass (the provider diffs a fid-on run against a
               fid-off run, so every claimed rename is witnessed).
* fid-ghidra - Ghidra FidService full+specific hash pairs of the target,
               looked up in the corpus fid_index.json built the same way.
               A (full, specific) hit is the strongest evidence this
               slice produces; a full-only hit is weaker (the specific
               hash exists to separate functions sharing a full hash).
* bsim       - BSim feature vectors (generated by Ghidra's own BSim
               signature generator) compared by cosine similarity against
               the corpus vectors. Probabilistic: a score is evidence,
               not proof, and is reported as such.
"""
import json
import math
import os

PLACEHOLDER_PREFIXES = ("FUN_", "sub_")


def is_placeholder(name):
    return not name or name.startswith(PLACEHOLDER_PREFIXES)


def load_fid_index(corpus_dir):
    p = os.path.join(corpus_dir, "fid_index.json")
    if not os.path.exists(p):
        return {}, {}
    data = json.load(open(p))
    full_specific = {}
    full_only = {}
    for e in data["entries"]:
        full_specific[(e["full_hash"], e["specific_hash"])] = e
        full_only.setdefault(e["full_hash"], []).append(e)
    return full_specific, full_only


def fid_ghidra_matches(ghidra_funcs, full_specific, full_only):
    out = {}
    for vaddr, rec in ghidra_funcs.items():
        fh, sh = rec.get("fid_full_hash"), rec.get("fid_specific_hash")
        if fh is None:
            continue
        hit = full_specific.get((fh, sh))
        if hit:
            out[vaddr] = {"method": "fid-ghidra", "strength": "full+specific",
                          "names": hit["names"], "builds": hit["builds"],
                          "evidence": {"full_hash": fh, "specific_hash": sh}}
        elif fh in full_only:
            names = sorted({n for e in full_only[fh] for n in e["names"]})
            builds = sorted({b for e in full_only[fh] for b in e["builds"]})
            out[vaddr] = {"method": "fid-ghidra", "strength": "full-only",
                          "names": names, "builds": builds,
                          "evidence": {"full_hash": fh, "specific_hash": sh}}
    return out


def fid_kuna_matches(kuna_with_fid, kuna_without_fid):
    """Names present only in the fid-on listing are FID identifications."""
    out = {}
    for addr, f in kuna_with_fid.items():
        base = kuna_without_fid.get(addr)
        if base is None:
            continue
        if is_placeholder(base["name"]) and not is_placeholder(f["name"]):
            out[addr] = {"method": "fid-kuna", "strength": "full-hash rename",
                         "names": [f["name"]], "builds": [],
                         "evidence": {"before": base["name"], "after": f["name"]}}
    return out


def cosine(v1, v2):
    if not v1 or not v2:
        return 0.0
    if len(v1) > len(v2):
        v1, v2 = v2, v1
    dot = sum(w * v2.get(k, 0.0) for k, w in v1.items())
    n1 = math.sqrt(sum(w * w for w in v1.values()))
    n2 = math.sqrt(sum(w * w for w in v2.values()))
    return dot / (n1 * n2) if n1 and n2 else 0.0


def bsim_matches(target_vectors, corpus_vectors, threshold=0.9, min_features=4):
    """target_vectors / corpus_vectors: parse_bsim_xml_dir records.

    Corpus records carry real names; target records are matched by
    normalized address (see ghidra_engine.parse_bsim_xml_dir caller).
    Returns {target_key: record}.

    Guards, both learned from measurement and stated plainly:
    - a vector with fewer than min_features distinct features carries
      too little information to support a claim (3-feature wrapper
      functions are vector-identical across whole families);
    - when distinct corpus functions tie at the top score, the match
      is recorded as ambiguous with every tied name attached, never
      resolved by iteration order (the hash *_Update siblings are
      vector-identical at 100+ features).
    """
    corpus = [c for c in corpus_vectors
              if not is_placeholder(c["name"])
              and len(c["vector"]) >= min_features]
    out = {}
    for t in target_vectors:
        if len(t["vector"]) < min_features:
            continue
        scored = [(cosine(t["vector"], c["vector"]), c) for c in corpus]
        scored = [(s, c) for s, c in scored if s >= threshold]
        if not scored:
            continue
        top = max(s for s, _c in scored)
        tied = [c for s, c in scored if top - s < 0.001]
        names = sorted({c["name"] for c in tied})
        builds = sorted({c.get("build", c["exe"]) for c in tied})
        if len(names) > 1:
            strength = "ambiguous"
        else:
            strength = "strong" if top >= 0.99 else "moderate"
        out[t["key"]] = {"method": "bsim", "strength": strength,
                         "names": names, "builds": builds,
                         "evidence": {"similarity": round(top, 4),
                                      "target_features": len(t["vector"]),
                                      "tied_names": names,
                                      "candidate_exes": sorted({c["exe"] for c in tied}),
                                      "candidate_addresses": sorted({c["address"] for c in tied})}}
    return out
